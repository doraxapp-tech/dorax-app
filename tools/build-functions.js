/* Dorax Finance — makes the server's copy of the reminder rules: supabase/functions/reminders/engine.mjs.
   Run: node tools/build-functions.js (npm run functions). With --check it only says whether the copy is up to date;
   with --version it prints the short name of the function's code, to compare with what the deployed function answers.

   Why: the job that sends reminders runs on the server, where there is no page. It must decide "what is due for this person today" with
   exactly the rules the app uses, and say it in exactly the app's words. So nothing is written twice: this script takes the app's own files
   (the calculations, the reminder wording, the formats, the translations that wording uses) and wraps them in one function,
   openAccount(account, today). Change a rule or a text in the app, run this, deploy the function, and the server follows.

   The app's files are plain scripts that share names (S, t, fmt...). Inside the wrapping function those names are local, so many accounts
   can be opened one after another without touching each other. */
const fs = require('fs'), path = require('path'), vm = require('vm');
const APP = path.join(__dirname, '..', 'app'), OUT = path.join(__dirname, '..', 'supabase', 'functions', 'reminders', 'engine.mjs');
const read = f => fs.readFileSync(path.join(APP, f), 'utf8');

// the calculations a reminder needs, in the order index.html loads them; the readers of files (statements, spreadsheets) are left out
const CORE = ['js/core/dates.js', 'js/core/reporting.js', 'js/core/plan.js', 'js/core/cards.js', 'js/core/reminders.js', 'js/core/goals.js', 'js/core/statements-owed.js', 'js/data/defaults.js'];
const TEXT = ['js/ui/translate.js', 'js/ui/format.js', 'js/features/reminders/reminder-messages.js'];
const order = [...read('index.html').matchAll(/<script src="([^"]+)"><\/script>/g)].map(m => m[1]);
for (const f of [...CORE, ...TEXT]) if (!order.includes(f)) throw new Error('build-functions: ' + f + ' is not a script of the app (index.html)');
const sorted = list => list.slice().sort((a, b) => order.indexOf(a) - order.indexOf(b));

// only the translations these files use: the full tables are a megabyte, the reminders need a few dozen rows
const ctx = vm.createContext({});
vm.runInContext(read('js/i18n/translations.js') + '\n' + read('js/i18n/voice.js') + '\n;globalThis.out = { I18N, VOICE: typeof VOICE === "undefined" ? {} : VOICE };', ctx);
const { I18N, VOICE } = ctx.out;
const sources = sorted(TEXT).map(read).join('\n');
const lit = "'((?:[^'\\\\]|\\\\.)*)'", unq = s => s.replace(/\\(.)/g, '$1');
const keys = new Set();
for (const m of sources.matchAll(new RegExp('\\bt\\(\\s*' + lit, 'g'))) keys.add(unq(m[1]));
for (const m of sources.matchAll(new RegExp('\\btn\\(\\s*[^,]+,\\s*' + lit + '\\s*,\\s*' + lit, 'g'))) { keys.add(unq(m[1])); keys.add(unq(m[2])); }
const missing = [...keys].filter(k => !(k in I18N.es) || !(k in I18N.pt));
if (missing.length) throw new Error('build-functions: no translation for ' + JSON.stringify(missing));
const pick = table => Object.fromEntries(Object.entries(table || {}).map(([lang, rows]) => [lang, Object.fromEntries([...keys].filter(k => rows && k in rows).map(k => [k, rows[k]]))]));

const body = `// GENERATED by tools/build-functions.js from the app's own files. Do not edit: change the app, then run "npm run functions".
// Files: ${[...sorted(CORE), ...sorted(TEXT)].join(', ')}

/** Opens one person's account as it is on a given day (today: 'YYYY-MM-DD') and says what there is to remind them of.
    account: the document kept in user_data.data. Returns { reminders, key, digest, push, lang, name, emailOn, texts }. */
export function openAccount(S, today) {
  const UI = { forceTone: null };
  S.today = today;
  const I18N = ${JSON.stringify(pick(I18N))};
  const VOICE = ${JSON.stringify(pick(VOICE))};
  const icon = () => '';
// ---------------------------------------------------------------- the app's files
${[...sorted(CORE), ...sorted(TEXT)].map(f => '// ---- ' + f + '\n' + read(f)).join('\n')}
// ---------------------------------------------------------------- what the job asks
  const CUR = BASE_CURRENCY;
  const user = S.user || {}, snoozed = (user.remind || {}).snoozed || {};
  const due = messageReminders(reminders(S, today, CUR, reminderOptions(S))).filter(r => snoozed[r.id] !== today);
  return { reminders: due, key: reminderKey, digest: reminderDigest, push: reminderPush, lang: (S.settings || {}).lang || 'pt', name: user.name || '',
    emailOn: !user.channels || user.channels.email !== false, texts: reminderTexts() };
}
`;
// --version: the short name of the code in supabase/functions/reminders as it is on this computer. The deployed function answers the same
// letters to { "action": "version" } when it runs these very files (see versionOf in logic.mjs).
if (process.argv.includes('--version')) {
  const at = f => require('url').pathToFileURL(path.join(path.dirname(OUT), f)).href;
  Promise.all(['logic.mjs', 'webpush.mjs', 'email.mjs'].map(f => import(at(f)))).then(async ([logic, webpush, email]) => { console.log(await logic.versionOf([...logic.PARTS, ...webpush.PARTS, ...email.PARTS])); }, e => { console.error('build-functions: ' + e.message); process.exit(1); });
  return;
}
// --check: says whether the server's copy is the one this script would write now, and changes nothing (the tests use it)
if (process.argv.includes('--check')) {
  const same = fs.existsSync(OUT) && fs.readFileSync(OUT, 'utf8') === body;
  console.log(same ? 'functions: engine.mjs is up to date' : 'functions: engine.mjs is OLDER than the app. Run "npm run functions", then deploy the function again.');
  process.exit(same ? 0 : 1);
}
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, body);
console.log('functions: engine.mjs,', Math.round(body.length / 1024), 'KB,', keys.size, 'texts in', Object.keys(I18N).length + 1, 'languages');
